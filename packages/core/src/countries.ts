export const COUNTRY_CODES = Object.keys(COUNTRY_NAMES_EN);

const cache = new Map<string, Intl.DisplayNames | null>();
/** Country name in the user's language ("France", "Royaume-Uni"), English if Intl.DisplayNames is missing. */
export function countryName(code: string, locale = "en"): string {
  const c = code.toUpperCase();
  if (!cache.has(locale)) {
    try {
      cache.set(locale, new Intl.DisplayNames([locale], { type: "region" }));
    } catch {
      cache.set(locale, null);
    }
  }
  try {
    return cache.get(locale)?.of(c) ?? COUNTRY_NAMES_EN[c] ?? c;
  } catch {
    return COUNTRY_NAMES_EN[c] ?? c;
  }
}

const norm = (s: string) => s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();

/** Countries matching a name (in the user's language or English) or a code; exact code first. */
export function searchCountries(query: string, locale = "en", limit = 8): { code: string; name: string }[] {
  const q = norm(query.trim());
  if (!q) return [];
  const out: { code: string; name: string; r: number }[] = [];
  for (const code of COUNTRY_CODES) {
    const name = countryName(code, locale);
    const n = norm(name);
    const en = norm(COUNTRY_NAMES_EN[code]!);
    const r = norm(code) === q ? 0 : n.startsWith(q) || en.startsWith(q) ? 1 : n.includes(q) || en.includes(q) ? 2 : 9;
    if (r < 9) out.push({ code, name, r });
  }
  return out.sort((a, b) => a.r - b.r || a.name.localeCompare(b.name)).slice(0, limit).map(({ code, name }) => ({ code, name }));
}

/** The ISO code of a country written by name (in French or English) or as a code; undefined when not found. */
export function countryCodeOf(nameOrCode: string | undefined | null): string | undefined {
  const s = (nameOrCode ?? "").trim();
  if (!s) return undefined;
  if (/^[A-Za-z]{2}$/.test(s) && countryName(s.toUpperCase(), "en") !== s.toUpperCase()) return s.toUpperCase();
  const norm = (x: string) => x.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
  for (const loc of ["fr", "en"]) {
    const hit = searchCountries(s, loc, 1)[0];
    if (hit && norm(hit.name) === norm(s)) return hit.code;
  }
  return undefined;
}
