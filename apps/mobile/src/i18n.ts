const DICTS: Record<Locale, Dict> = { en, fr };

export function deviceLocale(): Locale {
  try {
    return getLocales()[0]?.languageCode === "fr" ? "fr" : "en";
  } catch {
    return "en";
  }
}

export type TFunction = (key: I18nKey, params?: Record<string, string | number>) => string;

export function translator(locale: Locale): TFunction {
  const dict = DICTS[locale] ?? en;
  return (key, params) => {
    let s = dict[key] ?? en[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** Localised date (UTC calendar day), e.g. "10 nov. 2026". */
export function formatDate(date: string, locale: Locale): string {
  try {
    return new Intl.DateTimeFormat(locale === "fr" ? "fr-FR" : "en-GB", {
      day: "2-digit", month: "short", year: "numeric", timeZone: "UTC",
    }).format(new Date(`${date.slice(0, 10)}T00:00:00Z`));
  } catch {
    return date.slice(0, 10);
  }
}

export function formatMonth(yyyymm: string, locale: Locale): string {
  try {
    const s = new Intl.DateTimeFormat(locale === "fr" ? "fr-FR" : "en-GB", { month: "long", year: "numeric", timeZone: "UTC" }).format(
      new Date(`${yyyymm}-01T00:00:00Z`),
    );
    return s.charAt(0).toUpperCase() + s.slice(1);
  } catch {
    return yyyymm;
  }
}
